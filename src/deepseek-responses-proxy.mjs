import http from "node:http";
import { randomUUID } from "node:crypto";

const PORT = Number(process.env.PORT || process.env.DEEPSEEK_PROXY_PORT || 4000);
const HOST = process.env.DEEPSEEK_PROXY_HOST || "127.0.0.1";
const DEEPSEEK_BASE_URL = (process.env.DEEPSEEK_BASE_URL || "https://api.deepseek.com").replace(/\/+$/, "");
const DEEPSEEK_MODEL = process.env.DEEPSEEK_MODEL || "deepseek-chat";
const LOG_REQUESTS = process.env.LOG_REQUESTS === "1";
const DEEPSEEK_THINKING = process.env.DEEPSEEK_THINKING === "1" ? "enabled" : "disabled";
const IDENTITY_PROMPT_TEMPLATE =
  process.env.DEEPSEEK_IDENTITY_PROMPT ||
  "Provider bridge note: this response is generated by DeepSeek through the local Codex compatibility proxy. If asked about your model or provider, say you are DeepSeek using the {model} model via Codex, not an OpenAI GPT model.";

function responseId() {
  return `resp_${randomUUID().replaceAll("-", "")}`;
}

function messageId() {
  return `msg_${randomUUID().replaceAll("-", "")}`;
}

function json(res, status, body) {
  const payload = JSON.stringify(body);
  res.writeHead(status, {
    "content-type": "application/json; charset=utf-8",
    "content-length": Buffer.byteLength(payload),
  });
  res.end(payload);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    req.on("data", (chunk) => chunks.push(chunk));
    req.on("end", () => {
      try {
        const raw = Buffer.concat(chunks).toString("utf8");
        resolve(raw ? JSON.parse(raw) : {});
      } catch (error) {
        reject(error);
      }
    });
    req.on("error", reject);
  });
}

function extractText(content) {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return "";

  return content
    .map((part) => {
      if (typeof part === "string") return part;
      if (!part || typeof part !== "object") return "";
      return part.text || part.input_text || part.output_text || "";
    })
    .filter(Boolean)
    .join("\n");
}

function responseInputToMessages(body) {
  const messages = [];

  const identityPrompt = IDENTITY_PROMPT_TEMPLATE.replaceAll("{model}", body.model || DEEPSEEK_MODEL).trim();
  if (identityPrompt) {
    messages.push({ role: "system", content: identityPrompt });
  }

  if (typeof body.instructions === "string" && body.instructions.trim()) {
    messages.push({ role: "system", content: body.instructions });
  }

  const input = body.input;
  if (typeof input === "string") {
    messages.push({ role: "user", content: input });
    return messages;
  }

  if (!Array.isArray(input)) {
    return messages;
  }

  for (const item of input) {
    if (!item || typeof item !== "object") continue;

    if (item.type === "message" || item.role) {
      const role = item.role === "assistant" ? "assistant" : item.role === "system" ? "system" : "user";
      const content = extractText(item.content);
      if (content) messages.push({ role, content });
      continue;
    }

    if (item.type === "function_call_output") {
      const output = typeof item.output === "string" ? item.output : JSON.stringify(item.output ?? "");
      messages.push({
        role: "tool",
        tool_call_id: item.call_id || "unknown_call",
        content: output,
      });
      continue;
    }

    if (item.type === "function_call") {
      messages.push({
        role: "assistant",
        content: null,
        tool_calls: [
          {
            id: item.call_id || item.id || `call_${randomUUID().replaceAll("-", "")}`,
            type: "function",
            function: {
              name: item.name || "unknown_function",
              arguments: item.arguments || "{}",
            },
          },
        ],
      });
      continue;
    }

    const content = extractText(item.content);
    if (content) messages.push({ role: "user", content });
  }

  return messages;
}

function responsesToolsToChatTools(tools) {
  if (!Array.isArray(tools)) return undefined;

  const chatTools = tools
    .filter((tool) => tool && tool.type === "function" && tool.name)
    .map((tool) => ({
      type: "function",
      function: {
        name: tool.name,
        description: tool.description || "",
        parameters: tool.parameters || { type: "object", properties: {} },
      },
    }));

  return chatTools.length ? chatTools : undefined;
}

function buildChatPayload(body, stream) {
  const messages = responseInputToMessages(body);
  if (messages.length === 0) {
    messages.push({ role: "user", content: "" });
  }

  const tools = responsesToolsToChatTools(body.tools);
  const payload = {
    model: body.model || DEEPSEEK_MODEL,
    messages,
    stream,
    thinking: { type: DEEPSEEK_THINKING },
    temperature: typeof body.temperature === "number" ? body.temperature : undefined,
    top_p: typeof body.top_p === "number" ? body.top_p : undefined,
    max_tokens: typeof body.max_output_tokens === "number" ? body.max_output_tokens : undefined,
  };

  if (tools) {
    payload.tools = tools;
    payload.tool_choice = body.tool_choice && body.tool_choice !== "none" ? body.tool_choice : "auto";
  }

  return payload;
}

function responseEnvelope({ id, model, text = "", usage, status = "completed", outputItemId, input = [], instructions = null, output }) {
  const now = Math.floor(Date.now() / 1000);
  const content = [
    {
      type: "output_text",
      text,
      annotations: [],
    },
  ];

  return {
    id,
    object: "response",
    created_at: now,
    status,
    error: null,
    incomplete_details: null,
    instructions,
    max_output_tokens: null,
    model,
    output:
      output ??
      (status === "created" || status === "in_progress"
        ? []
        : [
            {
              id: outputItemId || messageId(),
              type: "message",
              status: "completed",
              role: "assistant",
                content,
            },
          ]),
    parallel_tool_calls: true,
    previous_response_id: null,
    reasoning: null,
    store: false,
    temperature: null,
    text: { format: { type: "text" } },
    tool_choice: "auto",
    tools: [],
    top_p: null,
    truncation: "disabled",
    input,
    usage: usage
      ? {
          input_tokens: usage.prompt_tokens ?? 0,
          output_tokens: usage.completion_tokens ?? 0,
          total_tokens: usage.total_tokens ?? 0,
        }
      : {
          input_tokens: 0,
          output_tokens: 0,
          total_tokens: 0,
        },
  };
}

function makeSseWriter(res) {
  let sequenceNumber = 0;
  return (event, data) => {
    sequenceNumber += 1;
    writeSse(res, event, data, sequenceNumber);
  };
}

function writeSse(res, event, data, sequenceNumber) {
  if (data && typeof data === "object" && !Array.isArray(data) && !data.type) {
    data = { type: event, ...data };
  }
  if (data && typeof data === "object" && !Array.isArray(data) && typeof data.sequence_number !== "number") {
    data = { ...data, sequence_number: sequenceNumber ?? 0 };
  }
  res.write(`event: ${event}\n`);
  res.write(`data: ${JSON.stringify(data)}\n\n`);
}

async function callDeepSeek(payload, apiKey) {
  return fetch(`${DEEPSEEK_BASE_URL}/chat/completions`, {
    method: "POST",
    headers: {
      authorization: `Bearer ${apiKey}`,
      "content-type": "application/json",
    },
    body: JSON.stringify(payload),
  });
}

async function handleNonStream(reqBody, req, res, apiKey) {
  const id = responseId();
  const chatPayload = buildChatPayload(reqBody, false);
  const upstream = await callDeepSeek(chatPayload, apiKey);
  const upstreamText = await upstream.text();

  if (!upstream.ok) {
    console.error(`[deepseek-proxy] upstream non-stream error ${upstream.status}: ${upstreamText.slice(0, 1000)}`);
    json(res, upstream.status, {
      error: {
        message: upstreamText || upstream.statusText,
        type: "deepseek_error",
        status: upstream.status,
      },
    });
    return;
  }

  const data = JSON.parse(upstreamText);
  const message = data.choices?.[0]?.message || {};
  const text = message.content || "";
  const output = [];

  if (text) {
    output.push({
      id: messageId(),
      type: "message",
      status: "completed",
      role: "assistant",
      content: [{ type: "output_text", text, annotations: [] }],
    });
  }

  for (const toolCall of message.tool_calls || []) {
    output.push({
      id: `fc_${randomUUID().replaceAll("-", "")}`,
      type: "function_call",
      status: "completed",
      call_id: toolCall.id || `call_${randomUUID().replaceAll("-", "")}`,
      name: toolCall.function?.name || "",
      arguments: toolCall.function?.arguments || "",
    });
  }

  json(
    res,
    200,
    responseEnvelope({
      id,
      model: chatPayload.model,
      text,
      usage: data.usage,
      input: reqBody.input || [],
      output: output.length ? output : undefined,
    }),
  );
}

async function handleStream(reqBody, req, res, apiKey) {
  const id = responseId();
  const outputItemId = messageId();
  let textOutputItem = null;
  let textContentPart = null;
  const toolOutputItems = new Map();
  const completedOutput = [];
  const chatPayload = buildChatPayload(reqBody, true);

  res.writeHead(200, {
    "content-type": "text/event-stream; charset=utf-8",
    "cache-control": "no-cache, no-transform",
    connection: "keep-alive",
    "x-accel-buffering": "no",
  });

  const send = makeSseWriter(res);
  const startedResponse = responseEnvelope({
    id,
    model: chatPayload.model,
    status: "in_progress",
    input: reqBody.input || [],
    instructions: reqBody.instructions ?? null,
  });

  send("response.created", {
    response: { ...startedResponse, status: "in_progress" },
  });
  send("response.in_progress", {
    response: { ...startedResponse, status: "in_progress" },
  });
  function addTextItem() {
    if (textOutputItem) return;
    textContentPart = { type: "output_text", text: "", annotations: [] };
    textOutputItem = {
      id: outputItemId,
      type: "message",
      status: "in_progress",
      role: "assistant",
      content: [],
    };
    send("response.output_item.added", { output_index: completedOutput.length, item: textOutputItem });
    send("response.content_part.added", {
      item_id: outputItemId,
      output_index: completedOutput.length,
      content_index: 0,
      part: textContentPart,
    });
  }

  function addToolItem(index, deltaToolCall) {
    if (toolOutputItems.has(index)) return toolOutputItems.get(index);

    const callId = deltaToolCall.id || `call_${randomUUID().replaceAll("-", "")}`;
    const item = {
      id: `fc_${randomUUID().replaceAll("-", "")}`,
      type: "function_call",
      status: "in_progress",
      call_id: callId,
      name: deltaToolCall.function?.name || "",
      arguments: "",
    };
    const entry = { item, outputIndex: completedOutput.length + toolOutputItems.size };
    toolOutputItems.set(index, entry);
    send("response.output_item.added", { output_index: entry.outputIndex, item });
    return entry;
  }

  const upstream = await callDeepSeek(chatPayload, apiKey);
  if (!upstream.ok || !upstream.body) {
    const message = await upstream.text();
    console.error(`[deepseek-proxy] upstream stream error ${upstream.status}: ${message.slice(0, 1000)}`);
    send("response.failed", {
      response: {
        id,
        object: "response",
        status: "failed",
        model: chatPayload.model,
        error: { message, type: "deepseek_error", status: upstream.status },
      },
    });
    res.end();
    return;
  }

  let fullText = "";
  let buffer = "";
  const decoder = new TextDecoder();

  for await (const chunk of upstream.body) {
    buffer += decoder.decode(chunk, { stream: true });
    const lines = buffer.split(/\r?\n/);
    buffer = lines.pop() || "";

    for (const line of lines) {
      if (!line.startsWith("data:")) continue;
      const raw = line.slice(5).trim();
      if (!raw || raw === "[DONE]") continue;

      let parsed;
      try {
        parsed = JSON.parse(raw);
      } catch {
        continue;
      }

      const delta = parsed.choices?.[0]?.delta?.content || "";
      if (delta) {
        addTextItem();
        fullText += delta;
        send("response.output_text.delta", {
          item_id: outputItemId,
          output_index: completedOutput.length,
          content_index: 0,
          delta,
        });
      }

      for (const toolCall of parsed.choices?.[0]?.delta?.tool_calls || []) {
        const index = Number.isInteger(toolCall.index) ? toolCall.index : 0;
        const entry = addToolItem(index, toolCall);
        if (toolCall.id && !entry.item.call_id) entry.item.call_id = toolCall.id;
        if (toolCall.function?.name) entry.item.name = toolCall.function.name;
        const argumentsDelta = toolCall.function?.arguments || "";
        if (argumentsDelta) {
          entry.item.arguments += argumentsDelta;
          send("response.function_call_arguments.delta", {
            item_id: entry.item.id,
            output_index: entry.outputIndex,
            delta: argumentsDelta,
          });
        }
      }
    }
  }

  if (textOutputItem && textContentPart) {
    textContentPart.text = fullText;
    textOutputItem.status = "completed";
    textOutputItem.content = [textContentPart];
    send("response.output_text.done", {
      item_id: outputItemId,
      output_index: completedOutput.length,
      content_index: 0,
      text: fullText,
    });
    send("response.content_part.done", {
      item_id: outputItemId,
      output_index: completedOutput.length,
      content_index: 0,
      part: textContentPart,
    });
    send("response.output_item.done", { output_index: completedOutput.length, item: textOutputItem });
    completedOutput.push(textOutputItem);
  }

  for (const entry of [...toolOutputItems.values()].sort((a, b) => a.outputIndex - b.outputIndex)) {
    entry.item.status = "completed";
    send("response.function_call_arguments.done", {
      item_id: entry.item.id,
      output_index: entry.outputIndex,
      arguments: entry.item.arguments,
    });
    send("response.output_item.done", { output_index: entry.outputIndex, item: entry.item });
    completedOutput.push(entry.item);
  }

  if (!textOutputItem && toolOutputItems.size === 0) {
    addTextItem();
    textContentPart.text = "";
    textOutputItem.status = "completed";
    textOutputItem.content = [textContentPart];
    send("response.output_text.done", {
      item_id: outputItemId,
      output_index: completedOutput.length,
      content_index: 0,
      text: "",
    });
    send("response.content_part.done", {
      item_id: outputItemId,
      output_index: completedOutput.length,
      content_index: 0,
      part: textContentPart,
    });
    send("response.output_item.done", { output_index: completedOutput.length, item: textOutputItem });
    completedOutput.push(textOutputItem);
  }

  send("response.completed", {
    response: responseEnvelope({
      id,
      model: chatPayload.model,
      text: fullText,
      outputItemId,
      input: reqBody.input || [],
      instructions: reqBody.instructions ?? null,
      output: completedOutput,
    }),
  });
  res.write("data: [DONE]\n\n");
  res.end();
}

async function handleResponses(req, res) {
  console.error(`[deepseek-proxy] inbound ${req.method} ${req.url} content-type=${req.headers["content-type"] || ""} content-encoding=${req.headers["content-encoding"] || ""}`);
  const apiKey = process.env.DEEPSEEK_API_KEY;
  if (!apiKey) {
    json(res, 500, { error: { message: "Missing DEEPSEEK_API_KEY", type: "configuration_error" } });
    return;
  }

  if (process.env.REQUIRE_PROXY_AUTH !== "0") {
    const expected = process.env.PROXY_AUTH_TOKEN || apiKey;
    const authorization = req.headers.authorization || "";
    if (authorization !== `Bearer ${expected}`) {
      json(res, 401, { error: { message: "Missing or invalid proxy bearer token", type: "authentication_error" } });
      return;
    }
  }

  let body;
  try {
    body = await readBody(req);
  } catch {
    console.error("[deepseek-proxy] invalid JSON request body");
    json(res, 400, { error: { message: "Invalid JSON request body", type: "invalid_request_error" } });
    return;
  }

  if (LOG_REQUESTS) {
    const summary = {
      model: body.model,
      stream: body.stream,
      input_type: Array.isArray(body.input) ? "array" : typeof body.input,
      input_items: Array.isArray(body.input) ? body.input.map((item) => item?.type || item?.role || typeof item) : undefined,
      tools: Array.isArray(body.tools) ? body.tools.map((tool) => tool?.type || tool?.name || "tool") : undefined,
    };
    console.error("[deepseek-proxy] /responses", JSON.stringify(summary));
  }

  if (body.stream) {
    await handleStream(body, req, res, apiKey);
  } else {
    await handleNonStream(body, req, res, apiKey);
  }
}

const server = http.createServer(async (req, res) => {
  try {
    const url = new URL(req.url || "/", `http://${req.headers.host || `${HOST}:${PORT}`}`);

    if (req.method === "GET" && url.pathname === "/health") {
      json(res, 200, { ok: true, provider: "deepseek", target: `${DEEPSEEK_BASE_URL}/chat/completions` });
      return;
    }

    if (req.method === "POST" && (url.pathname === "/responses" || url.pathname === "/v1/responses")) {
      await handleResponses(req, res);
      return;
    }

    json(res, 404, { error: { message: `No route for ${req.method} ${url.pathname}`, type: "not_found" } });
  } catch (error) {
    json(res, 500, { error: { message: error?.message || "Unexpected proxy error", type: "proxy_error" } });
  }
});

server.listen(PORT, HOST, () => {
  console.error(`[deepseek-proxy] listening on http://${HOST}:${PORT}`);
  console.error(`[deepseek-proxy] forwarding to ${DEEPSEEK_BASE_URL}/chat/completions`);
});
