function normalizeDeepSeekModel(requestedModel) {
  const requested = typeof requestedModel === "string" ? requestedModel.trim() : "";
  const normalized = requested.toLowerCase();

  if (normalized === "deepseek-v4-pro") return "deepseek-v4-pro";
  if (normalized === "deepseek-v4-flash") return "deepseek-v4-flash";
  if (normalized === "gpt-5.2") return "deepseek-v4-flash";
  if (normalized === "gpt-5.3-codex") return "deepseek-v4-pro";

  return null;
}

function normalizeThinkingMode(value) {
  const normalized = typeof value === "string" ? value.trim().toLowerCase() : "";
  if (["off", "none", "false", "disabled"].includes(normalized)) return "disabled";
  if (["on", "true", "enabled", "high"].includes(normalized)) return "high";
  if (normalized === "max") return "max";
  return "disabled";
}

function resolveUpstreamModel(requestedModel) {
  const mapped = normalizeDeepSeekModel(requestedModel);
  if (!mapped) return null;
  activeModel = loadActiveModel();
  activeThinkingMode = loadThinkingMode();
  return activeModel || mapped;
}

function loadActiveModel() {
  if (ACTIVE_MODEL_STATE_FILE && existsSync(ACTIVE_MODEL_STATE_FILE)) {
    try {
      const saved = readFileSync(ACTIVE_MODEL_STATE_FILE, "utf8").trim();
      return normalizeDeepSeekModel(saved) || DEFAULT_ACTIVE_MODEL;
    } catch {
      return DEFAULT_ACTIVE_MODEL;
    }
  }
  return DEFAULT_ACTIVE_MODEL;
}

function saveActiveModel(model) {
  activeModel = model;
  if (!ACTIVE_MODEL_STATE_FILE) return;
  try {
    writeFileSync(ACTIVE_MODEL_STATE_FILE, `${model}\n`, "utf8");
  } catch (error) {
    console.error(`[deepseek-proxy] failed to save active model state: ${error?.message || error}`);
  }
}

function loadThinkingMode() {
  if (THINKING_MODE_STATE_FILE && existsSync(THINKING_MODE_STATE_FILE)) {
    try {
      return normalizeThinkingMode(readFileSync(THINKING_MODE_STATE_FILE, "utf8"));
    } catch {
      return DEFAULT_THINKING_MODE;
    }
  }
  return DEFAULT_THINKING_MODE;
}

function saveThinkingMode(mode) {
  activeThinkingMode = normalizeThinkingMode(mode);
  if (!THINKING_MODE_STATE_FILE) return;
  try {
    writeFileSync(THINKING_MODE_STATE_FILE, `${activeThinkingMode}\n`, "utf8");
  } catch (error) {
    console.error(`[deepseek-proxy] failed to save thinking mode state: ${error?.message || error}`);
  }
}

function switchThinkingMode(mode = "") {
  if (mode === "max") {
    saveThinkingMode("max");
  } else if (["high", "on", "enabled"].includes(mode)) {
    saveThinkingMode("high");
  } else if (["off", "disabled", "none"].includes(mode)) {
    saveThinkingMode("disabled");
  } else {
    saveThinkingMode(activeThinkingMode === "disabled" ? "high" : "disabled");
  }
  return activeThinkingMode;
}

function toggleActiveModel() {
  const next = activeModel === "deepseek-v4-pro" ? "deepseek-v4-flash" : "deepseek-v4-pro";
  saveActiveModel(next);
  return next;
}

function switchActiveModelFromCommand(text) {
  const normalized = text.trim().toLowerCase();
  let next = "";
  if (/\b(pro|v4-pro|deepseek-v4-pro)\b/.test(normalized)) {
    next = "deepseek-v4-pro";
  } else if (/\b(flash|v4-flash|deepseek-v4-flash)\b/.test(normalized)) {
    next = "deepseek-v4-flash";
  } else {
    next = toggleActiveModel();
    return next;
  }

  saveActiveModel(next);
  return next;
}

function readResidentContext() {
  if (!RESIDENT_CONTEXT_FILE || !existsSync(RESIDENT_CONTEXT_FILE)) return "";
  try {
    const content = readFileSync(RESIDENT_CONTEXT_FILE, "utf8");
    return content.slice(0, RESIDENT_CONTEXT_MAX_CHARS).trim();
  } catch (error) {
    console.error(`[deepseek-proxy] failed to read resident context: ${error?.message || error}`);
    return "";
  }
}

function json(res, status, body) {
  const payload = JSON.stringify(body);
  res.writeHead(status, {
    "content-type": "application/json; charset=utf-8",
    "content-length": Buffer.byteLength(payload),
  });
  res.end(payload);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    req.on("data", (chunk) => chunks.push(chunk));
    req.on("end", () => {
      try {
        const raw = Buffer.concat(chunks).toString("utf8");
        resolve(raw ? JSON.parse(raw) : {});
      } catch (error) {
        reject(error);
      }
    });
    req.on("error", reject);
  });
}

function extractText(content) {
  if (typeof content === "string") return content;
  if (!content || typeof content !== "object") return "";
  if (!Array.isArray(content)) {
    return content.text || content.input_text || content.output_text || "";
  }

  return content
    .map((part) => {
      if (typeof part === "string") return part;
      if (!part || typeof part !== "object") return "";
      return part.text || part.input_text || part.output_text || "";
    })
    .filter(Boolean)
    .join("\n");
}

function extractItemText(item) {
  if (!item || typeof item !== "object") return "";
  return (
    extractText(item.content) ||
    item.text ||
    item.input_text ||
    item.output_text ||
    ""
  );
}

function getLatestUserText(body) {
  const input = body?.input;
  if (typeof input === "string") return input.trim();
  if (!Array.isArray(input)) return "";

  for (let i = input.length - 1; i >= 0; i -= 1) {
    const item = input[i];
    if (!item || typeof item !== "object") continue;
    const role = item.role || (item.type === "message" ? item.role : "");
    if (role && role !== "user") continue;
    const text = extractItemText(item).trim();
    if (text) return text;
  }

  return "";
}

function normalizeCommandText(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/^\/+/, "")
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function parseDeepSeekCommand(text) {
  const normalized = normalizeCommandText(text);
  if (!normalized) return null;

  const withoutPrefix = normalized.startsWith("d ") ? normalized.slice(2).trim() : normalized;
  const tokens = withoutPrefix.split(" ").filter(Boolean);
  const [name, ...args] = tokens;
  if (!name) return null;

  if (["help", "model", "context"].includes(name) && args.length === 0) {
    return { name, args: [] };
  }

  if (name === "switch") {
    const filteredArgs = args.filter((arg) => arg !== "to");
    if (filteredArgs.length === 0) return { name: "switch", args: [] };
    const joinedArgs = filteredArgs.join(" ");
    if (["pro", "v4 pro", "deepseek v4 pro"].includes(joinedArgs)) {
      return { name: "switch", args: ["pro"] };
    }
    if (["flash", "v4 flash", "deepseek v4 flash"].includes(joinedArgs)) {
      return { name: "switch", args: ["flash"] };
    }
    return null;
  }

  if (name === "think" || name === "thinking") {
    if (args.length === 0) return { name: "think", args: [] };
    if (args.length === 1 && ["high", "max", "off", "on", "enabled", "disabled", "none"].includes(args[0])) {
      return { name: "think", args: [args[0]] };
    }
    return null;
  }

  return null;
}

function isDeepSeekCommand(text) {
  return Boolean(parseDeepSeekCommand(text));
}

function commandName(text) {
  const parsed = parseDeepSeekCommand(text);
  return parsed ? [parsed.name, ...parsed.args].join(" ") : "";
}

function handleDeepSeekCommand(text) {
  const parsed = parseDeepSeekCommand(text);
  if (parsed?.name === "switch") {
    const switchedModel = parsed.args[0] === "pro"
      ? switchActiveModelFromCommand("pro")
      : parsed.args[0] === "flash"
        ? switchActiveModelFromCommand("flash")
        : switchActiveModelFromCommand("");
    return {
      model: switchedModel,
      text: `已切换成 ${switchedModel}。`,
    };
  }

  if (parsed?.name === "model") {
    return {
      model: activeModel,
      text: `当前模型：${activeModel}。Thinking：${activeThinkingMode}。`,
    };
  }

  if (parsed?.name === "context") {
    const loaded = Boolean(readResidentContext());
    return {
      model: activeModel,
      text: loaded ? "常驻上下文：已加载。" : "常驻上下文：未生成或为空。重新启动 DeepSeek Codex 可自动刷新。",
    };
  }

  if (parsed?.name === "think") {
    const mode = switchThinkingMode(parsed.args[0] || "");
    return {
      model: activeModel,
      text: `DeepSeek thinking：${mode}。`,
    };
  }

  return {
    model: activeModel,
    text: [
      "DeepSeek Codex 指令：",
      "/D-switch：切换 Pro / Flash",
      "/D-switch pro：切换到 Pro",
      "/D-switch flash：切换到 Flash",
      "/D-model：查看当前模型",
      "/D-context：查看常驻上下文状态",
      "/D-think：切换 thinking high / off",
      "/D-think high|max|off：设置 thinking 模式",
    ].join("\n"),
  };
}

function isIgnorableResponseItem(item) {
  return (
    item?.type === "reasoning" ||
    item?.type === "custom_tool_call" ||
    item?.type === "custom_tool_call_output"
  );
}

function responseFunctionCallToToolCall(item) {
  const callId = item.call_id || item.id || `call_${randomUUID().replaceAll("-", "")}`;
  return {
    id: callId,
    type: "function",
    function: {
      name: item.name || "unknown_function",
      arguments: item.arguments || "{}",
    },
  };
}

function responseToolOutputToMessage(item) {
  const output = typeof item.output === "string" ? item.output : JSON.stringify(item.output ?? "");
  return {
    role: "tool",
    tool_call_id: item.call_id || "unknown_call",
    content: output,
  };
}

function responseInputToMessages(body, upstreamModel) {
  const messages = [];

  const identityPrompt = IDENTITY_PROMPT_TEMPLATE.replaceAll("{model}", upstreamModel || DEEPSEEK_MODEL).trim();
  if (identityPrompt) {
    messages.push({ role: "system", content: identityPrompt });
  }

  if (typeof body.instructions === "string" && body.instructions.trim()) {
    messages.push({ role: "system", content: body.instructions });
  }

  if (LANGUAGE_PROMPT.trim()) {
    messages.push({ role: "system", content: LANGUAGE_PROMPT.trim() });
  }

  const residentContext = readResidentContext();
  if (residentContext) {
    messages.push({
      role: "system",
      content: [
        "Optional resident project background supplied by the local DeepSeek context tool.",
        "This is not the Codex chat-window context. Treat chat messages, attached files, selected code, tool results, and the latest user request as authoritative when they conflict.",
        "",
        residentContext,
      ].join("\n"),
    });
  }

  const input = body.input;
  if (typeof input === "string") {
    messages.push({ role: "user", content: input });
    return messages;
  }

  if (!Array.isArray(input)) {
    return messages;
  }

  for (let i = 0; i < input.length; i += 1) {
    const item = input[i];
    if (!item || typeof item !== "object") continue;

    if (isIgnorableResponseItem(item)) continue;

    if (item.type === "function_call") {
      const toolCalls = [];
      while (i < input.length) {
        const callItem = input[i];
        if (!callItem || typeof callItem !== "object" || callItem.type !== "function_call") break;
        toolCalls.push(responseFunctionCallToToolCall(callItem));
        i += 1;
      }

      const toolMessages = [];
      while (i < input.length) {
        const outputItem = input[i];
        if (!outputItem || typeof outputItem !== "object") break;
        if (isIgnorableResponseItem(outputItem)) {
          i += 1;
          continue;
        }
        if (outputItem.type !== "function_call_output") break;
        toolMessages.push(responseToolOutputToMessage(outputItem));
        i += 1;
      }
      i -= 1;

      const expectedCallIds = new Set(toolCalls.map((toolCall) => toolCall.id));
      const actualCallIds = new Set(toolMessages.map((message) => message.tool_call_id));
      const hasCompleteToolOutputs =
        toolCalls.length > 0 &&
        toolMessages.length === toolCalls.length &&
        [...expectedCallIds].every((callId) => actualCallIds.has(callId));

      if (hasCompleteToolOutputs) {
        messages.push({
          role: "assistant",
          content: null,
          tool_calls: toolCalls,
        });
        messages.push(...toolMessages);
      }
      continue;
    }

    if (item.type === "function_call_output") {
      continue;
    }

    if (item.type === "message" || item.role) {
      const role = item.role === "assistant" ? "assistant" : item.role === "system" ? "system" : "user";
      const content = extractText(item.content);
      if (content) messages.push({ role, content });
      continue;
    }

    const content = extractText(item.content);
    if (content) messages.push({ role: "user", content });
  }

  return messages;
}

function responsesToolsToChatTools(tools) {
  if (!Array.isArray(tools)) return undefined;

  const chatTools = tools
    .filter((tool) => tool && tool.type === "function" && tool.name)
    .map((tool) => ({
      type: "function",
      function: {
        name: tool.name,
        description: tool.description || "",
        parameters: tool.parameters || { type: "object", properties: {} },
      },
    }));

  return chatTools.length ? chatTools : undefined;
}

function inputContainsToolWorkflow(input) {
  if (!Array.isArray(input)) return false;
  return input.some((item) => {
    if (!item || typeof item !== "object") return false;
    const type = item.type || "";
    if (
      type === "function_call" ||
      type === "function_call_output" ||
      type === "tool_call" ||
      type === "tool_result"
    ) {
      return true;
    }
    if (Array.isArray(item.content)) {
      return item.content.some((part) => {
        const partType = part?.type || "";
        return partType === "function_call" || partType === "function_call_output" || partType === "tool_result";
      });
    }
    return false;
  });
}

function isToolWorkflowRequest(body, chatTools) {
  return Boolean(
    (Array.isArray(chatTools) && chatTools.length > 0) ||
      (Array.isArray(body?.tools) && body.tools.length > 0) ||
      inputContainsToolWorkflow(body?.input),
  );
}

function buildChatPayload(body, stream, upstreamModel) {
  const messages = responseInputToMessages(body, upstreamModel);
  if (messages.length === 0) {
    messages.push({ role: "user", content: "" });
  }

  const tools = responsesToolsToChatTools(body.tools);
  const effectiveThinkingMode = isToolWorkflowRequest(body, tools) ? "disabled" : activeThinkingMode;
  if (activeThinkingMode !== "disabled" && effectiveThinkingMode === "disabled") {
    console.error("[deepseek-proxy] thinking disabled for tool workflow request");
  }
  const payload = {
    model: upstreamModel,
    messages,
    stream,
    thinking: { type: effectiveThinkingMode === "disabled" ? "disabled" : "enabled" },
    reasoning_effort: effectiveThinkingMode === "disabled" ? undefined : effectiveThinkingMode,
    temperature: typeof body.temperature === "number" ? body.temperature : undefined,
    top_p: typeof body.top_p === "number" ? body.top_p : undefined,
    max_tokens: typeof body.max_output_tokens === "number" ? body.max_output_tokens : undefined,
  };

  if (tools) {
    payload.tools = tools;
    payload.tool_choice = body.tool_choice && body.tool_choice !== "none" ? body.tool_choice : "auto";
  }

  return payload;
}

